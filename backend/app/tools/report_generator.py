import uuid
from datetime import datetime, timezone
from typing import Dict, Any, List
import app.core.database as db
from app.models.artifact import Artifact
from app.storage.local_storage import storage

async def report_generator_tool(params: Dict[str, Any], user_id: str, execution_id: str) -> Dict[str, Any]:
    title = params.get("title", "Nexus AI Strategic Research & Analysis Report")
    summary = params.get("executive_summary", "")
    methodology = params.get("methodology", "Multi-agent autonomous planning, research extraction, and empirical synthesis.")
    findings = params.get("findings", [])
    evidence = params.get("evidence", [])
    limitations = params.get("limitations", "Findings are subject to the completeness of retrieved sources and public disclosures.")

    # Format Markdown document
    md_lines = [
        f"# {title}",
        f"\n**Generated by**: Nexus AI Autonomous Agent Operating Platform",
        f"**Date**: {datetime.now(timezone.utc).strftime('%B %d, %Y - %H:%M:%S UTC')}",
        f"**Execution ID**: `{execution_id}`",
        "\n---\n",
        "## 1. Executive Summary\n",
        summary if summary else "This report synthesizes objective research findings and analysis gathered through automated agent workflows.",
        "\n## 2. Methodology\n",
        methodology,
        "\n## 3. Key Findings & Detailed Analysis\n"
    ]

    if isinstance(findings, list) and findings:
        for idx, item in enumerate(findings, 1):
            if isinstance(item, dict):
                heading = item.get("topic") or item.get("title") or f"Finding {idx}"
                content = item.get("content") or item.get("details") or str(item)
                md_lines.append(f"### 3.{idx} {heading}\n\n{content}\n")
            else:
                md_lines.append(f"### 3.{idx} Finding\n\n{item}\n")
    else:
        md_lines.append("Detailed analysis points synthesized across verified data sources.\n")

    md_lines.extend([
        "## 4. Supporting Evidence & References\n"
    ])

    if isinstance(evidence, list) and evidence:
        for idx, ev in enumerate(evidence, 1):
            if isinstance(ev, dict):
                url = ev.get("url", "#")
                src_title = ev.get("title", f"Source {idx}")
                snippet = ev.get("snippet", "")
                md_lines.append(f"- **[{src_title}]({url})**: {snippet}")
            else:
                md_lines.append(f"- {ev}")
    else:
        md_lines.append("- Primary evidence extracted from configured agent research streams.")

    md_lines.extend([
        "\n## 5. Limitations & Risk Factors\n",
        limitations,
        "\n---\n",
        "*Nexus AI Operating Platform — Verified Automated Intelligence Artifact*"
    ])

    report_content = "\n".join(md_lines).encode("utf-8")
    artifact_id = str(uuid.uuid4())
    storage_key = f"reports/{execution_id}/{artifact_id}.md"

    # Save to storage
    await storage.save(storage_key, report_content)

    # Save artifact record in database
    async with db.AsyncSessionLocal() as session:
        art = Artifact(
            id=artifact_id,
            owner_id=user_id,
            execution_id=execution_id,
            artifact_type="report_markdown",
            storage_key=storage_key,
            meta_info={
                "title": title,
                "byte_size": len(report_content),
                "format": "markdown",
                "citations_count": len(evidence) if isinstance(evidence, list) else 0
            }
        )
        session.add(art)
        await session.commit()

    return {
        "artifact_id": artifact_id,
        "title": title,
        "storage_key": storage_key,
        "format": "markdown",
        "size_bytes": len(report_content),
        "success": True
    }
